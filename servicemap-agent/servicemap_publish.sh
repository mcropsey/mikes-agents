#!/bin/bash
# Publish the lab service map to github.com/mcropsey/cropsey-lab (service-map/) when it changed.
# Runs as mcropsey (pushes over HTTPS with the token in ~/.git-credentials). --force publishes anyway.
set -euo pipefail
export HOME=$(getent passwd "$(id -un)" | cut -d: -f6)
SRC=${SERVICEMAP_SITE:-/opt/labagents/data/servicemap/site}
REPO=${SERVICEMAP_REPO:-$HOME/cropsey-lab}
DEST=$REPO/service-map
FILES="index.html README.md servicemap.json fleet-dark.svg fleet-light.svg ai-map-dark.svg ai-map-light.svg"

field() { python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get(sys.argv[2], ""))' "$1" "$2" 2>/dev/null || true; }

new=$(field "$SRC/servicemap.json" fingerprint)
[ -n "$new" ] || { echo "no map in $SRC; run servicemap first" >&2; exit 1; }
cd "$REPO"
if [ -n "$(git status --porcelain -- service-map)" ]; then
  echo "uncommitted edits under $DEST; not publishing (commit or discard them first)" >&2; exit 1
fi
git pull -q --ff-only
old=$(field "$DEST/servicemap.json" fingerprint)
if [ "$new" = "$old" ] && [ "${1:-}" != "--force" ]; then
  echo "map unchanged (fingerprint $new); nothing to publish"; exit 0
fi
mkdir -p "$DEST"
for f in $FILES; do cp "$SRC/$f" "$DEST/$f"; done
summary=$(field "$SRC/servicemap.json" change_summary)
git add -- service-map
git commit -q -m "service-map: $(date +%F) - ${summary:-update}" \
  -m "Generated by servicemap-agent on 192.168.1.98 (fingerprint $new)." -- service-map
git push -q
echo "published $(git rev-parse --short HEAD): ${summary:-update}"
